export function normalizeUiLocale(value) {
  return normalizeLanguageLocale(value) ?? DEFAULT_UI_LOCALE;
}

function catalogMessage(locale, namespace, key, catalog) {
  if (!catalog || !Array.isArray(catalog.packs)) return null;
  const normalized = normalizeUiLocale(locale);
  for (const pack of catalog.packs) {
    if (pack?.locale === normalized && pack.namespace === namespace && Object.hasOwn(pack.messages ?? {}, key)) return pack.messages[key];
  }
  return null;
}

export function translateUi(locale, key, catalog = null) {
  const normalized = normalizeUiLocale(locale);
  return catalogMessage(normalized, 'atlas', key, catalog) ?? brandDefaultUiCopy(MESSAGES[normalized]?.[key] ?? MESSAGES.en[key] ?? key);
}

export function translateModuleUi(locale, namespace, key, catalog = null, fallbackMessages = {}) {
  if (typeof namespace !== 'string' || !namespace || namespace === 'atlas') throw new TypeError('Module namespace must be a non-atlas namespace.');
  const override = catalogMessage(locale, namespace, key, catalog);
  return override ?? (typeof fallbackMessages?.[key] === 'string' ? fallbackMessages[key] : key);
}
