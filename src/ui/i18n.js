export function normalizeLanguageLocale(value) {
  if (typeof value !== 'string' || value.length < 2 || value.length > 35 || !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8}){0,2}$/u.test(value)) return null;
  const parts = value.split('-');
  const normalized = parts.map((part, index) => {
    if (index === 0) return part.toLowerCase();
    if (/^[A-Za-z]{2}$/u.test(part)) return part.toUpperCase();
    if (/^[0-9]{3}$/u.test(part)) return part;
    if (/^[A-Za-z]{4}$/u.test(part)) return `${part[0].toUpperCase()}${part.slice(1).toLowerCase()}`;
    if (/^[A-Za-z0-9]{5,8}$/u.test(part)) return part.toLowerCase();
    return null;
  });
  return normalized.every(Boolean) ? normalized.join('-') : null;
}

